"""Generated parts of the documentation book in docs/book.

  python -I scripts/docs_book.py reference --cli target/debug/processcraft-cli.exe [--check]
      Writes (or, with --check, verifies) the CLI and batch-command reference pages and the command
      schema from the live `processcraft-cli` output, so the reference cannot drift from the code.

  python -I scripts/docs_book.py agents BUILD_DIR
      After `mdbook build docs/book`: copies each page's Markdown (includes expanded) next to its
      HTML page as .md, and writes llms.txt (an index) and llms-full.txt (every page) into BUILD_DIR/html.
"""
import argparse
import json
import pathlib
import re
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "docs" / "book" / "src"
REF = SRC / "reference"
SITE = "https://eliobenigni7.github.io/ProcessCraft/docs/"
NOTICE = "<!-- Generated by scripts/docs_book.py from processcraft-cli. Do not edit by hand. -->\n\n"


def run(cli, *args):
    out = subprocess.run([cli, *args], capture_output=True, check=True, text=True, encoding="utf-8").stdout
    return out.replace("\r\n", "\n").replace("processcraft-cli.exe", "processcraft-cli")


def subcommands(cli):
    help_text = run(cli, "--help")
    block = help_text.split("Commands:\n", 1)[1].split("\n\n", 1)[0]
    names = [line.split()[0] for line in block.splitlines() if line.startswith("  ") and line.split()]
    return [n for n in names if n != "help"]


def cli_page(cli):
    parts = [NOTICE, "# Reference: CLI subcommands\n\n",
             "Every subcommand of `processcraft-cli`, with the help text it prints. "
             "`processcraft-cli <subcommand> --help` shows the same on your machine.\n\n"]
    names = subcommands(cli)
    parts.append("".join(f"- [`{n}`](#{n})\n" for n in names) + "\n")
    for n in names:
        parts.append(f"## {n}\n\n```text\n{run(cli, n, '--help').rstrip()}\n```\n\n")
    return "".join(parts).rstrip() + "\n"


def commands_page(descriptors):
    parts = [NOTICE, "# Reference: batch commands\n\n",
             f"The {len(descriptors)} commands a batch can contain. The canvas, the CLI (`run --batch`) "
             "and the MCP `apply` tool all accept exactly these. Each is a JSON object whose `type` is "
             "the command name; parameter names are `snake_case`. Required parameters are in bold.\n\n"
             "The full JSON Schema of the request protocol is [commands.json](commands.json), the "
             "output of `processcraft-cli commands --json`. "
             "[Batches and the command pipeline](../developers/batches.md) explains how they are applied.\n\n",
             "| Command | What it does | Parameters |\n|---|---|---|\n"]
    for d in sorted(descriptors, key=lambda d: d["serde_tag"]):
        params = ", ".join(
            (f"**`{p['name']}`**" if p["required"] else f"`{p['name']}`") + f" ({p['value_type'].replace('|', ' or ')})"
            for p in d["params"])
        parts.append(f"| `{d['serde_tag']}` | {d['label']} | {params or 'none'} |\n")
    return "".join(parts)


def reference(args):
    args.cli = str(pathlib.Path(args.cli).resolve())
    schema_text = run(args.cli, "commands", "--json")
    descriptors = json.loads(schema_text)["commands"]
    wanted = {
        REF / "cli.md": cli_page(args.cli),
        REF / "commands.md": commands_page(descriptors),
        REF / "commands.json": json.dumps(json.loads(schema_text), indent=1, ensure_ascii=False) + "\n",
    }
    stale = []
    for path, text in wanted.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            if args.check:
                stale.append(path.relative_to(ROOT).as_posix())
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    if stale:
        print("stale generated docs (run scripts/docs_book.py reference):", *stale, sep="\n  ")
        return 1
    print("reference up to date" if args.check else "reference written")
    return 0


def agents(args):
    build = pathlib.Path(args.build_dir)
    md_dir, html_dir = build / "markdown", build / "html"
    summary = (SRC / "SUMMARY.md").read_text(encoding="utf-8")
    index = ["# ProcessCraft documentation\n\n",
             "> ProcessCraft is an offline desktop workbench for BPMN processes, with a CLI and a "
             "local MCP server that run the same typed commands as the canvas. Every page below is "
             "also available as Markdown at the same path with a .md extension.\n\n"]
    full = []
    for line in summary.splitlines():
        if line.startswith("# ") and line != "# Summary":
            index.append(f"\n## {line[2:]}\n\n")
        for title, link in re.findall(r"\[([^\]]+)\]\(([^)]+\.md)\)", line):
            link = link[:-len("README.md")] + "index.md" if link.endswith("README.md") else link  # mdBook serves README as index
            page = md_dir / link
            target = html_dir / link
            shutil.copyfile(page, target)
            index.append(f"- [{title}]({SITE}{link}): {SITE}{link[:-3]}.html\n")
            full.append(page.read_text(encoding="utf-8").rstrip() + "\n")
    (html_dir / "llms.txt").write_text("".join(index), encoding="utf-8", newline="\n")
    (html_dir / "llms-full.txt").write_text("\n\n---\n\n".join(full), encoding="utf-8", newline="\n")
    print(f"agent files written for {len(full)} pages")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("reference")
    r.add_argument("--cli", required=True)
    r.add_argument("--check", action="store_true")
    a = sub.add_parser("agents")
    a.add_argument("build_dir")
    args = parser.parse_args()
    return reference(args) if args.cmd == "reference" else agents(args)


if __name__ == "__main__":
    sys.exit(main())
