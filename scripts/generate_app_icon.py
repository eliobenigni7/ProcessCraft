"""Generate the ProcessCraft app icon from one geometry: SVG master, PNG sizes and Windows .ico.

The icon follows the Crafting Apps tile conventions (512-unit tile, rx=112, three colours:
ink, paper and the app colour) with original artwork: a slightly tilted sheet of paper carrying
a small BPMN process (start event, task, exclusive gateway with a rework loop, end event).

Usage:  python scripts/generate_app_icon.py          (writes assets/app-icon/)
Requires Pillow.
"""
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "app-icon"

INK = "#0b0b0c"
PAPER = "#efe9dc"
AMBER = "#f2a516"  # ProcessCraft app colour
TILT = -6  # degrees, around the tile centre

# Geometry in 512-unit tile space, before the paper tilt.
PAGE = (84, 96, 428, 424)  # x0, y0, x1, y1
FOLD = 56  # folded top-right corner
LANE = (84, 96, 126, 424)  # lane header band, in the app colour
FLOW_Y = 252
START = (166, FLOW_Y, 21)  # cx, cy, r
TASK = (210, 214, 292, 290, 16)  # x0, y0, x1, y1, corner radius
GATE = (356, FLOW_Y, 34)  # cx, cy, half diagonal
END = (356, 372, 21)  # below the gateway, reached by a downward branch
LOOP_Y = 160  # rework loop: gateway top -> up -> left -> task top
TITLE = []  # x0, y, x1 title lines (none: room for the process)


def svg() -> str:
    x0, y0, x1, y1 = PAGE
    sx, sy, sr = START
    tx0, ty0, tx1, ty1, tr = TASK
    gx, gy, gh = GATE
    ex, ey, er = END
    tcx = (tx0 + tx1) / 2
    title = " ".join(f"M{a} {y} H{b}" for a, y, b in TITLE)
    title_path = f'      <path d="{title}" fill="none" stroke-width="12"/>\n' if title else ""
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">
  <!-- ProcessCraft app icon: a sheet of paper carrying a small BPMN process (start event, task,
       exclusive gateway with a rework loop, end event) on the ProcessCraft amber tile.
       Original work for ProcessCraft; generated by scripts/generate_app_icon.py.
       Palette: ink {INK}, paper {PAPER}, app colour {AMBER}. -->
  <defs>
    <clipPath id="tile"><rect width="512" height="512" rx="112"/></clipPath>
    <marker id="arrow" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="4" markerHeight="4" orient="auto">
      <path d="M0 0 L10 5 L0 10 Z" fill="{INK}"/>
    </marker>
  </defs>
  <g clip-path="url(#tile)">
    <rect width="512" height="512" fill="{AMBER}"/>
    <g transform="rotate({TILT} 256 256)" stroke="{INK}" stroke-linejoin="round" stroke-linecap="round">
      <path d="M{x0} {y0} H{x1 - FOLD} L{x1} {y0 + FOLD} V{y1} H{x0} Z" fill="{PAPER}" stroke-width="14"/>
      <path d="M{x1 - FOLD} {y0} V{y0 + FOLD} H{x1}" fill="none" stroke-width="12"/>
      <path d="M{LANE[0] + 7} {LANE[1] + 7} H{LANE[2]} V{LANE[3] - 7} H{LANE[0] + 7} Z" fill="{AMBER}" stroke="none"/>
      <path d="M{LANE[2]} {LANE[1]} V{LANE[3]}" fill="none" stroke-width="10"/>
{title_path}      <circle cx="{sx}" cy="{sy}" r="{sr}" fill="{PAPER}" stroke-width="9"/>
      <rect x="{tx0}" y="{ty0}" width="{tx1 - tx0}" height="{ty1 - ty0}" rx="{tr}" fill="{PAPER}" stroke-width="12"/>
      <path d="M{gx} {gy - gh} L{gx + gh} {gy} L{gx} {gy + gh} L{gx - gh} {gy} Z" fill="{AMBER}" stroke-width="12"/>
      <path d="M{gx - 10} {gy - 10} L{gx + 10} {gy + 10} M{gx + 10} {gy - 10} L{gx - 10} {gy + 10}" fill="none" stroke-width="8"/>
      <circle cx="{ex}" cy="{ey}" r="{er}" fill="{INK}" stroke-width="6"/>
      <path d="M{sx + sr} {sy} H{tx0 - 6}" fill="none" stroke-width="9" marker-end="url(#arrow)"/>
      <path d="M{tx1} {gy} H{gx - gh - 6}" fill="none" stroke-width="9" marker-end="url(#arrow)"/>
      <path d="M{gx} {gy + gh} V{ey - er - 6}" fill="none" stroke-width="9" marker-end="url(#arrow)"/>
      <path d="M{gx} {gy - gh} V{LOOP_Y} H{tcx} V{ty0 - 6}" fill="none" stroke-width="9" marker-end="url(#arrow)"/>
    </g>
  </g>
</svg>
"""


def png(size: int) -> Image.Image:
    """Rasterise the same geometry with Pillow at 4x, then downsample."""
    s = 4 * 512
    k = s / 512
    sc = lambda v: v * k  # noqa: E731
    tile = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    ImageDraw.Draw(tile).rounded_rectangle((0, 0, s - 1, s - 1), radius=sc(112), fill=AMBER)
    art = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(art)
    w = lambda v: max(1, round(v * k))  # noqa: E731
    x0, y0, x1, y1 = PAGE
    page = [(x0, y0), (x1 - FOLD, y0), (x1, y0 + FOLD), (x1, y1), (x0, y1)]
    d.polygon([(sc(x), sc(y)) for x, y in page], fill=PAPER)
    d.rectangle((sc(LANE[0] + 7), sc(LANE[1] + 7), sc(LANE[2]), sc(LANE[3] - 7)), fill=AMBER)
    d.line([(sc(x), sc(y)) for x, y in page + [page[0]]], fill=INK, width=w(14), joint="curve")
    d.line([(sc(x1 - FOLD), sc(y0)), (sc(x1 - FOLD), sc(y0 + FOLD)), (sc(x1), sc(y0 + FOLD))], fill=INK, width=w(12), joint="curve")
    d.line([(sc(LANE[2]), sc(LANE[1])), (sc(LANE[2]), sc(LANE[3]))], fill=INK, width=w(10))
    for a, y, b in TITLE:
        d.line([(sc(a), sc(y)), (sc(b), sc(y))], fill=INK, width=w(12))
        for cx in (a, b):
            r = 6 * k
            d.ellipse((sc(cx) - r, sc(y) - r, sc(cx) + r, sc(y) + r), fill=INK)

    def arrow(points, head=True):
        pts = [(sc(x), sc(y)) for x, y in points]
        d.line(pts, fill=INK, width=w(9), joint="curve")
        if head:
            (ax, ay), (bx, by) = points[-2], points[-1]
            dx, dy = (bx - ax), (by - ay)
            n = (dx * dx + dy * dy) ** 0.5 or 1
            ux, uy = dx / n, dy / n
            tip = (bx + ux * 6, by + uy * 6)
            size = 16
            left = (tip[0] - ux * size - uy * size * 0.6, tip[1] - uy * size + ux * size * 0.6)
            right = (tip[0] - ux * size + uy * size * 0.6, tip[1] - uy * size - ux * size * 0.6)
            d.polygon([(sc(x), sc(y)) for x, y in (tip, left, right)], fill=INK)

    sx, sy, sr = START
    tx0, ty0, tx1, ty1, tr = TASK
    gx, gy, gh = GATE
    ex, ey, er = END
    tcx = (tx0 + tx1) / 2
    arrow([(sx + sr, sy), (tx0 - 6, sy)])
    arrow([(tx1, gy), (gx - gh - 6, gy)])
    arrow([(gx, gy + gh), (ex, ey - er - 6)])
    arrow([(gx, gy - gh), (gx, LOOP_Y), (tcx, LOOP_Y), (tcx, ty0 - 6)])
    d.ellipse((sc(sx - sr), sc(sy - sr), sc(sx + sr), sc(sy + sr)), fill=PAPER, outline=INK, width=w(9))
    d.rounded_rectangle((sc(tx0), sc(ty0), sc(tx1), sc(ty1)), radius=sc(tr), fill=PAPER, outline=INK, width=w(12))
    diamond = [(gx, gy - gh), (gx + gh, gy), (gx, gy + gh), (gx - gh, gy)]
    d.polygon([(sc(x), sc(y)) for x, y in diamond], fill=AMBER)
    d.line([(sc(x), sc(y)) for x, y in diamond + [diamond[0]]], fill=INK, width=w(12), joint="curve")
    d.line([(sc(gx - 10), sc(gy - 10)), (sc(gx + 10), sc(gy + 10))], fill=INK, width=w(8))
    d.line([(sc(gx + 10), sc(gy - 10)), (sc(gx - 10), sc(gy + 10))], fill=INK, width=w(8))
    d.ellipse((sc(ex - er), sc(ey - er), sc(ex + er), sc(ey + er)), fill=INK)
    art = art.rotate(-TILT, resample=Image.BICUBIC, center=(s / 2, s / 2))
    mask = tile.split()[3]
    composed = Image.alpha_composite(tile, art)
    composed.putalpha(mask)
    return composed.resize((size, size), Image.LANCZOS)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "processcraft.svg").write_text(svg(), encoding="utf-8", newline="\n")
    master = png(1024)
    for size in (16, 32, 48, 64, 128, 256, 512, 1024):
        (master if size == 1024 else master.resize((size, size), Image.LANCZOS)).save(OUT / f"processcraft-{size}.png")
    master.save(OUT / "processcraft.ico", sizes=[(s, s) for s in (16, 24, 32, 48, 64, 128, 256)])
    print("wrote", OUT)


if __name__ == "__main__":
    main()
